def find_place(question: str):
    """
    从用户问题中识别地名，返回匹配信息。

    参数:
        question: 用户问题，如"我在土门"

    返回:
        {
            "found": True/False,
            "place": "土门",           # 识别到的地名
            "district": "莲湖区",      # 所属区域
            "stations": ["汉城路", "大庆路", "玉祥门"],  # 推荐附近的站点
            "lines": "总部1号线、总部3号线、...",        # 对应线路
            "ambiguous": False,        # 是否多区域（如钟楼→莲湖区/碑林区）
            "alternatives": []         # 如果ambiguous=True，列出可能的区域
        }
        或 {"found": False}
    """
    # 按地名长度降序排列，优先匹配长地名（如"曲江池遗址公园" > "曲江池"）
    sorted_places = sorted(PLACE_TO_DISTRICT.keys(), key=len, reverse=True)

    matched_place = None
    for place in sorted_places:
        if place in question:
            matched_place = place
            break

    if not matched_place:
        return {"found": False}

    district = PLACE_TO_DISTRICT[matched_place]

    # 判断是否跨区域（如"钟楼→莲湖区/碑林区"）
    ambiguous = "/" in district
    alternatives = district.split("/") if ambiguous else []

    # 获取推荐站点
    if matched_place in PLACE_NEARBY_STATIONS:
        stations = PLACE_NEARBY_STATIONS[matched_place]
    else:
        # 从所属区域获取站点
        primary_district = alternatives[0].strip() if ambiguous else district
        stations = DISTRICT_STATIONS.get(primary_district, [])

    # 获取线路信息
    if not ambiguous:
        lines = DISTRICT_LINES.get(district, "")
    else:
        lines = ""
        for alt in alternatives:
            alt = alt.strip()
            alt_lines = DISTRICT_LINES.get(alt, "")
            if alt_lines:
                lines += f"{alt}：{alt_lines}、"

    return {
        "found": True,
        "place": matched_place,
        "district": district,
        "stations": stations[:5],  # 最多返回5个站点
        "lines": lines,
        "ambiguous": ambiguous,
        "alternatives": alternatives,
    }


def find_district_in_question(question: str):
    """
    检测问题中是否直接提到了区域名（如"雁塔区"、"莲湖区"）。

    返回区域名或None。
    """
    districts = ["未央区", "雁塔区", "长安区", "莲湖区", "碑林区", "新城区",
                 "灞桥区", "曲江新区", "经开区", "高新区", "西咸新区",
                 "咸阳市区", "泾渭/高陵", "高陵区", "秦都区", "渭城区",
                 "未央", "雁塔", "长安", "莲湖", "碑林", "新城",
                 "灞桥", "曲江", "经开", "高新", "咸阳", "秦汉", "沣西",
                 "泾渭", "高陵"]

    # 按长度降序
    sorted_districts = sorted(districts, key=len, reverse=True)
    for d in sorted_districts:
        if d in question:
            return d
    return None